/**
 * Referrer-Policy matters because an invite link can carry the passcode.
 * The CSP allows inline scripts because the App Router ships them.
 */
const apiBase = process.env.NEXT_PUBLIC_API_BASE || "";
const wsBase = apiBase.startsWith("https")
  ? "wss" + apiBase.slice(5)
  : apiBase.startsWith("http")
    ? "ws" + apiBase.slice(4)
    : "";

const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self' data:",
  "img-src 'self' data: blob:",
  "media-src 'self' blob:",
  ["connect-src 'self'", apiBase, wsBase].filter(Boolean).join(" "),
].join("; ");

/** @type {import('next').NextConfig} */
const nextConfig = {
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "no-referrer" },
          {
            key: "Permissions-Policy",
            value: "geolocation=(), microphone=(self), camera=(self)",
          },
          {
            key: "Strict-Transport-Security",
            value: "max-age=31536000; includeSubDomains",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
